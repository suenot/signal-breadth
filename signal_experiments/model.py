"""Generative ground truth for correlated trading signals.

We model a strategy run across ``N`` correlated instruments ("pairs"). Each
instrument ``i`` emits a *binary activation* (in a position / flat) at each of
``T`` time steps, with marginal activation probability ``p`` (the "trading time"
of the source blog post). Activations are generated by thresholding a latent
Gaussian vector with a controllable correlation structure, so the ground-truth
*latent* correlation is known exactly and is cleanly separated from the
*realized binary-signal* correlation (these differ -- a central point of the
paper).

Two structures are provided:

* **Equicorrelation** -- ``z_{i,t} = sqrt(rho)*F_t + sqrt(1-rho)*eps_{i,t}``.
  Every pair has the same latent correlation ``rho``; this is the homogeneous
  world the blog post's ``N_eff = N/(1+(N-1)rho)`` formula implicitly assumes.
* **One-factor with heterogeneous loadings + optional blocks** -- each pair has
  its own loading ``b_i`` on a common factor (and optionally on a block/sector
  factor). Pairwise correlations are then *unequal*, which is where a single
  scalar ``rho_bar`` plugged into the equicorrelation formula should break.

Each active step also produces a *return*: a draw whose sign/scale is tied to
the same latent factor, so that strategies that activate together also tend to
win/lose together (correlated PnL). The realized portfolio variance reduction
is the ground-truth notion of "effective breadth" we validate against.

Everything is deterministic given a seeded ``numpy`` Generator. The latent
construction is positive-semidefinite by design; we additionally expose and
print the PSD-valid range ``rho >= -1/(N-1)`` for the equicorrelation case,
which the blog post ignores.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np
from scipy import stats

Structure = Literal["equicorr", "factor"]


# --------------------------------------------------------------------------- #
# config
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class SignalConfig:
    """Ground-truth signal-generating process for one simulated portfolio."""

    n_pairs: int = 10            # N instruments running the same strategy
    p_active: float = 0.10       # marginal activation prob per pair per step
    rho: float = 0.30            # latent equicorrelation OR mean factor-implied corr
    structure: Structure = "equicorr"
    t_steps: int = 20_000        # time steps simulated

    # --- heterogeneous one-factor params (used when structure == "factor") --
    n_blocks: int = 1            # >1 adds block/sector factors (heterogeneity)
    loading_dispersion: float = 0.0   # spread of per-pair common-factor loadings
    block_share: float = 0.0     # variance share carried by block factors

    # --- return model -----------------------------------------------------
    edge_per_trade: float = 0.05   # mean return of an active trade (the "edge")
    trade_vol: float = 1.0         # idiosyncratic per-trade return volatility
    # How strongly trade returns load on the common factor. NOT a hidden
    # constant: ``sample_config`` draws it from SAMPLED_BETA_GRID because the
    # headline breadth-accuracy biases (and their signs) depend on it.
    factor_return_beta: float = 0.6

    label: str = "custom"


# --------------------------------------------------------------------------- #
# PSD-valid range for equicorrelation
# --------------------------------------------------------------------------- #
def equicorr_psd_floor(n: int) -> float:
    """Smallest valid equicorrelation for an ``n x n`` matrix: ``-1/(n-1)``.

    Below this the equicorrelation matrix is not positive semidefinite, so it is
    not a valid correlation matrix. The blog post's formula ignores this bound.
    """
    return -1.0 / (n - 1) if n > 1 else -1.0


def is_psd_valid_equicorr(n: int, rho: float) -> bool:
    return rho >= equicorr_psd_floor(n) - 1e-12 and rho <= 1.0 + 1e-12


# --------------------------------------------------------------------------- #
# latent correlation builders
# --------------------------------------------------------------------------- #
def _equicorr_loadings(cfg: SignalConfig) -> tuple[np.ndarray, np.ndarray]:
    """Return ``(B, idio_sd)`` for the equicorrelation case as a degenerate
    one-factor model: a single factor with loading ``sqrt(rho)`` shared by all,
    idiosyncratic sd ``sqrt(1-rho)``. Each ``z_i`` has unit variance."""
    n = cfg.n_pairs
    if not is_psd_valid_equicorr(n, cfg.rho):
        raise ValueError(
            f"rho={cfg.rho} outside PSD-valid equicorrelation range "
            f"[{equicorr_psd_floor(n):.4f}, 1] for N={n}"
        )
    # negative equicorrelation cannot come from a single nonneg-variance factor;
    # build it directly via its known closed-form root for full generality.
    b = np.full((n, 1), np.sqrt(max(cfg.rho, 0.0)))
    idio = np.sqrt(max(1.0 - cfg.rho, 0.0))
    idio_sd = np.full(n, idio)
    return b, idio_sd


def _factor_loadings(cfg: SignalConfig, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    """Heterogeneous one-factor (+ optional block factors) loading matrix.

    Column 0 is the common ("BTC") factor; columns 1.. are block factors. Each
    row (pair) is scaled so its latent variance is exactly 1, giving a valid
    correlation matrix with *unequal* pairwise correlations whose mean is ~rho.

    Rows whose factor variance would exceed ``0.97**2`` (possible when a large
    common loading combines with a block loading) are renormalized -- the whole
    loading row is scaled down, preserving its relative structure -- so the total
    latent variance is exactly 1. Without this, the latent variance could reach
    ~1.19 and the realized activation probability would silently exceed the
    configured ``p``.
    """
    n = cfg.n_pairs
    # common-factor loadings centered so mean implied common correlation ~ rho
    base = np.sqrt(max(cfg.rho - cfg.block_share, 0.0))
    common = base + cfg.loading_dispersion * (rng.uniform(-1.0, 1.0, size=n))
    common = np.clip(common, 0.0, 0.97)

    n_factors = 1 + (cfg.n_blocks if cfg.n_blocks > 1 else 0)
    b = np.zeros((n, n_factors))
    b[:, 0] = common
    if cfg.n_blocks > 1 and cfg.block_share > 0:
        block_id = np.arange(n) % cfg.n_blocks
        block_load = np.sqrt(cfg.block_share)
        for k in range(cfg.n_blocks):
            b[block_id == k, 1 + k] = block_load
    # renormalize any row whose factor variance exceeds the cap, preserving the
    # row's relative loading structure; then idiosyncratic variance tops each
    # row up to *exactly* unit latent variance (no silent clipping).
    factor_var = np.sum(b**2, axis=1)
    cap = 0.97**2
    over = factor_var > cap
    if over.any():
        b[over, :] *= np.sqrt(cap / factor_var[over])[:, None]
        factor_var = np.sum(b**2, axis=1)
    idio_var = 1.0 - factor_var  # >= 1 - cap > 0 by construction
    return b, np.sqrt(idio_var)


def latent_loadings(cfg: SignalConfig, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    if cfg.structure == "equicorr":
        return _equicorr_loadings(cfg)
    return _factor_loadings(cfg, rng)


def latent_corr(cfg: SignalConfig, rng: np.random.Generator) -> np.ndarray:
    """Population latent correlation matrix implied by the loadings (N, N)."""
    b, idio_sd = latent_loadings(cfg, rng)
    cov = b @ b.T + np.diag(idio_sd**2)
    if cfg.structure == "equicorr" and cfg.rho < 0:
        # closed-form negative equicorrelation matrix (PSD on its valid range)
        n = cfg.n_pairs
        cov = (1.0 - cfg.rho) * np.eye(n) + cfg.rho * np.ones((n, n))
    d = np.sqrt(np.diag(cov))
    return cov / np.outer(d, d)


# --------------------------------------------------------------------------- #
# simulation
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class SimulatedSignals:
    activations: np.ndarray   # (T, N) bool: strategy in-position
    returns: np.ndarray       # (T, N) float: realized per-step return (0 if flat)
    latent: np.ndarray        # (T, N) float: the latent Gaussian (for diagnostics)
    corr_latent: np.ndarray   # (N, N) population latent correlation
    threshold: float          # Phi^{-1}(1-p): latent cutoff for activation
    cfg: SignalConfig


def _draw_latent(cfg: SignalConfig, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    """Draw the (T, N) latent Gaussian with the configured correlation, plus the
    (T,) common-factor series used to tie returns together."""
    n, t = cfg.n_pairs, cfg.t_steps
    if cfg.structure == "equicorr" and cfg.rho < 0:
        # sample directly from the PSD equicorrelation matrix via Cholesky
        corr = latent_corr(cfg, rng)
        chol = np.linalg.cholesky(corr)
        z = rng.standard_normal((t, n)) @ chol.T
        factor = z.mean(axis=1)  # proxy common factor for the return model
        return z, factor

    b, idio_sd = latent_loadings(cfg, rng)
    n_factors = b.shape[1]
    factors = rng.standard_normal((t, n_factors))
    idio = rng.standard_normal((t, n)) * idio_sd[None, :]
    z = factors @ b.T + idio
    return z, factors[:, 0]


def simulate(cfg: SignalConfig, rng: np.random.Generator) -> SimulatedSignals:
    """Generate activations + returns from the latent Gaussian model."""
    z, factor = _draw_latent(cfg, rng)
    threshold = float(stats.norm.ppf(1.0 - cfg.p_active))
    active = z > threshold

    # trade returns: idiosyncratic edge + common-factor co-movement, only when active
    beta = cfg.factor_return_beta
    fac_norm = (factor - factor.mean()) / (factor.std() + 1e-12)
    idio_ret = rng.standard_normal((cfg.t_steps, cfg.n_pairs))
    raw = cfg.edge_per_trade + cfg.trade_vol * (
        beta * fac_norm[:, None] + np.sqrt(max(1.0 - beta**2, 0.0)) * idio_ret
    )
    returns = np.where(active, raw, 0.0)

    return SimulatedSignals(
        activations=active,
        returns=returns,
        latent=z,
        corr_latent=latent_corr(cfg, rng),
        threshold=threshold,
        cfg=cfg,
    )


# --------------------------------------------------------------------------- #
# random sampler for Monte-Carlo batches
# --------------------------------------------------------------------------- #
# The ACTUAL sampled design of the main batch (reported verbatim in the paper).
SAMPLED_N_GRID: tuple[int, ...] = (5, 8, 10, 15, 20, 30)
SAMPLED_P_GRID: tuple[float, ...] = (0.05, 0.10, 0.15, 0.25, 0.45)
SAMPLED_BETA_GRID: tuple[float, ...] = (0.0, 0.3, 0.6, 0.9)
SAMPLED_RHO_RANGE: tuple[float, float] = (0.0, 0.7)


def sample_config(
    rng: np.random.Generator,
    *,
    structure: Structure | Literal["random"] = "random",
    t_steps: int = 20_000,
) -> SignalConfig:
    """Draw a diverse, PSD-valid config spanning homogeneous and heterogeneous
    correlation structures and a range of (N, p, rho, beta).

    ``factor_return_beta`` -- how strongly trade returns load on the common
    factor -- is an explicit sampled parameter (``SAMPLED_BETA_GRID``), NOT a
    hidden constant: the accuracy and even the *sign* of the bias of the
    equicorrelation N_eff against the realized PnL effective N depend on it.
    """
    n = int(rng.choice(SAMPLED_N_GRID))
    p = float(rng.choice(SAMPLED_P_GRID))
    # keep rho inside the PSD range and away from the degenerate top
    rho = float(np.clip(rng.uniform(*SAMPLED_RHO_RANGE),
                        max(equicorr_psd_floor(n), 0.0), 0.95))
    beta = float(rng.choice(SAMPLED_BETA_GRID))

    if structure == "random":
        structure = rng.choice(["equicorr", "factor"], p=[0.5, 0.5])

    if structure == "equicorr":
        return SignalConfig(
            n_pairs=n, p_active=p, rho=rho, structure="equicorr",
            factor_return_beta=beta, t_steps=t_steps, label="equicorr",
        )

    # heterogeneous one-factor, possibly with blocks
    n_blocks = int(rng.choice([1, 2, 3]))
    block_share = float(rng.uniform(0.0, 0.25)) if n_blocks > 1 else 0.0
    block_share = min(block_share, max(rho - 0.02, 0.0))
    dispersion = float(rng.uniform(0.1, 0.45))
    return SignalConfig(
        n_pairs=n, p_active=p, rho=rho, structure="factor",
        n_blocks=n_blocks, loading_dispersion=dispersion, block_share=block_share,
        factor_return_beta=beta, t_steps=t_steps, label=f"factor_b{n_blocks}",
    )


def canonical_configs(t_steps: int = 40_000) -> dict[str, SignalConfig]:
    """Illustrative configs used by the setup figure and sanity tests."""
    return {
        "homogeneous": SignalConfig(
            n_pairs=10, p_active=0.10, rho=0.30, structure="equicorr",
            t_steps=t_steps, label="homogeneous"),
        "heterogeneous": SignalConfig(
            n_pairs=10, p_active=0.10, rho=0.30, structure="factor",
            loading_dispersion=0.40, t_steps=t_steps, label="heterogeneous"),
        "blocky": SignalConfig(
            n_pairs=12, p_active=0.10, rho=0.35, structure="factor",
            n_blocks=3, block_share=0.20, loading_dispersion=0.25,
            t_steps=t_steps, label="blocky"),
        "weak": SignalConfig(
            n_pairs=10, p_active=0.10, rho=0.05, structure="equicorr",
            t_steps=t_steps, label="weak"),
    }
